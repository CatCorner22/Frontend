// Writes THIRD_PARTY_NOTICES.md from the packages that ship inside the Studio.
// Font licenses (SIL OFL 1.1) require that the copyright notice and license travel with the font files.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const pkg = (name) => JSON.parse(readFileSync(new URL(`node_modules/${name}/package.json`, root), 'utf8'));
const licenseText = (name) => {
  for (const file of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md']) {
    const url = new URL(`node_modules/${name}/${file}`, root);
    if (existsSync(url)) return readFileSync(url, 'utf8');
  }
  return '';
};
// Keep real copyright statements, not sentences of the license text that merely begin with the word.
const copyrightLines = (text) => [...new Set(text.split('\n').map((l) => l.trim()).filter((l) => /^copyright\b/i.test(l) && !/^copyright\s+(holder|statement|notice)/i.test(l)))].slice(0, 3).map((l) => (l.length > 160 ? `${l.slice(0, 157)}...` : l));

const fonts = readdirSync(new URL('node_modules/@fontsource-variable/', root)).map((dir) => `@fontsource-variable/${dir}`);
const runtime = ['react', 'react-dom', 'zustand', 'zod'];

let out = '# Third-party notices\n\nThe Studio ships these open-source works inside its page. This file is generated by `node scripts/make-notices.mjs`; do not edit it by hand.\n\n';
out += '## Fonts\n\nEach font is distributed under its own license, shown below. Under the SIL Open Font License 1.1, the fonts may be bundled and used commercially; they may not be sold by themselves; and the copyright notice and the license must accompany every copy. The full license text for each font is in `node_modules/<package>/LICENSE`, and a future export that includes font files must carry it too.\n\n| Font package | Version | License | Copyright |\n|---|---|---|---|\n';
for (const name of fonts) {
  const p = pkg(name);
  out += `| \`${name}\` | ${p.version} | ${p.license ?? 'see package'} | ${copyrightLines(licenseText(name)).join(' / ').replace(/\|/g, '/') || 'see the package LICENSE file'} |\n`;
}
out += '\n## Code\n\n| Package | Version | License | Copyright |\n|---|---|---|---|\n';
for (const name of runtime) {
  const p = pkg(name);
  out += `| \`${name}\` | ${p.version} | ${p.license ?? 'see package'} | ${copyrightLines(licenseText(name)).join(' / ').replace(/\|/g, '/') || 'see the package LICENSE file'} |\n`;
}
out += '\n## Ideas restated in our own words\n\nThe Catalog restates guidance from published sources in its own words and names each source in the Step that uses it. No source text is copied. Sources include the Vercel Web Interface Guidelines (MIT), the skills published by Emil Kowalski and Jakub Krehel (MIT), the Anthropic frontend-design skill (Apache-2.0), and Radix Colors (MIT). The color-space conversion in `packages/core/src/color.ts` uses the OKLab constants published by Björn Ottosson (public domain).\n';
writeFileSync(new URL('THIRD_PARTY_NOTICES.md', root), out);
console.log(`notices: ${fonts.length} fonts, ${runtime.length} code packages`);
