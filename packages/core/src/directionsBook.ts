// The book of Directions (SPEC.md section 2.20; decision D74): one markdown file that describes every built-in Direction in code.
// The owner asked for a file that says each design, its colors, and the rest, in the language of code, and asked that these looks
// always stay in the app. The core writes the file from the Catalog itself, so the file cannot drift from the Studio; a test
// compares it with the stored copy in `docs/reference/directions.md` and names each Direction that must stay.
import { DIRECTIONS, DIRECTION_GROUPS, type Direction } from './catalog/directions.js';
import { skinsOf } from './catalog/skins.js';
import { applyDirection, createProject } from './engine.js';
import { tokensCss } from './vision.js';
import { deriveTokens } from './tokens.js';

const BASIS_WORDS: Record<string, string> = {
  builder: 'composed by the assistant that wrote the Studio',
  snippet: 'a search summary',
  read: 'a page that was read',
  abstract: 'an abstract that was read',
  'owner-file': 'a file of the owner',
};

/** The design values of a Direction, or of one of its Skins, as the Studio works them out for a new project. */
function tokensOf(direction: Direction, skinId?: string): Record<string, string> {
  const project = applyDirection(createProject('Book of Directions'), direction, skinId);
  return deriveTokens(project.params, project.a11y).css;
}

function directionPart(direction: Direction): string[] {
  const out: string[] = [`### ${direction.name} (\`${direction.id}\`)`, ''];
  out.push(`- **Mood:** ${direction.mood}`);
  out.push(`- **Best for:** ${direction.bestFor}`);
  out.push(`- **Watch out:** ${direction.risk}`);
  for (const source of direction.sources) out.push(`- **Source (${BASIS_WORDS[source.basis] ?? source.basis}):** ${source.text}${source.record ? ` File: \`${source.record}\`.` : ''}`);
  for (const departure of direction.departs ?? []) out.push(`- **Departs on purpose from the research rule \`${departure.ruleId}\`:** ${departure.why}`);
  out.push('');
  out.push('**Design settings** (the Studio’s own values for this Direction; `DesignParams` in `packages/core/src/params.ts`):', '');
  out.push('```json', JSON.stringify(direction.params, null, 2), '```', '');
  out.push('**Colors, type, spacing, corners, and motion** (the `tokens.css` that a new project from this Direction gets):', '');
  out.push('```css', tokensCss(tokensOf(direction)).trimEnd(), '```', '');
  const skins = skinsOf(direction);
  if (skins.length > 0) {
    out.push('**Skins** (other colors, same layout). The main colors of each, as `tokens.css` names them:', '');
    out.push('| Skin | `--bg` | `--surface` | `--text` | `--accent` | `--accent-2` | `--btn-fill` |', '|---|---|---|---|---|---|---|');
    for (const skin of skins) {
      const css = tokensOf(direction, skin.id);
      out.push(`| ${skin.name} | \`${String(css['--bg'])}\` | \`${String(css['--surface'])}\` | \`${String(css['--text'])}\` | \`${String(css['--accent'])}\` | \`${String(css['--accent-2'])}\` | \`${String(css['--btn-fill'])}\` |`);
    }
    out.push('');
  }
  return out;
}

/** The whole book: an introduction, a list of the Directions by group, and one part for each Direction. */
export function directionsBook(): string {
  const out: string[] = ['# The Directions of Frontend Focus Studio, in code', ''];
  out.push('A Direction is a complete starting look that the owner picks before the Steps. This file describes each of the Studio’s built-in Directions in code: its mood in plain words, its design settings, every design value that a new project from it gets (colors, typefaces, sizes, spacing, corners, shadows, and motion, as CSS custom properties), and the main colors of each of its Skins.', '');
  out.push('**Do not edit this file by hand.** The Studio’s core writes it from the Catalog (`directionsBook` in `packages/core/src/directionsBook.ts`). A test compares this file with what the core writes, so the file always matches the Studio. To write it again after a change to the Catalog, run `npm run directions`. A second test names every Direction that the owner has seen; a Direction cannot leave the Catalog without that test failing (decision D74).', '');
  out.push('**Your own Directions are not in this file.** A Direction that you make in the Studio is kept in your browser, not in this repository. To keep a copy, press “Download my own Directions” in the Studio (it shows under “Your own”), keep the file, and bring them back later with “Open a file of own Directions”.', '');
  out.push('How to read a part: the design settings are the Studio’s inputs; the `tokens.css` block is what the Studio works out from them, and what an AI coding tool builds with. A color written `#rrggbb` is opaque; `rgb(r g b / a)` is partly transparent. The typefaces are named in `--font-heading` and `--font-body`.', '');
  out.push('## Contents', '');
  for (const group of DIRECTION_GROUPS) {
    const members = DIRECTIONS.filter((d) => d.group === group.id);
    out.push(`- **${group.label}:** ${members.map((d) => d.name).join(', ')}`);
  }
  out.push('');
  for (const group of DIRECTION_GROUPS) {
    out.push(`## ${group.label}`, '');
    for (const direction of DIRECTIONS.filter((d) => d.group === group.id)) out.push(...directionPart(direction));
  }
  return `${out.join('\n').trimEnd()}\n`;
}
