// The book of Directions (SPEC.md section 2.20; decision D74): one markdown file that describes every built-in Direction in code:
// its design settings, every design value of its `tokens.css`, and the main colors of each of its Skins. The core writes the
// file from the Catalog; the stored copy in `docs/reference/directions.md` must equal what the core writes today, so that the
// file never drifts from the Studio. The owner asked that these looks always stay in the app: a Direction that this test names
// cannot leave the Catalog without this test failing.
import { describe, expect, it } from 'vitest';
import { DIRECTIONS, DIRECTION_GROUPS, applyDirection, createProject, deriveTokens, directionsBook, skinsOf } from '../src/index.js';

/** The 38 built-in Directions of 2026-11-17. A new Direction may join; none of these may go without the owner's word (decision D74). */
const KEPT = [
  'graphite-precision', 'midnight-aurora', 'ember-noir', 'paper-and-ink', 'soft-daylight', 'poster-block', 'sticker-pop', 'clinical-calm',
  'evening-formal', 'control-room', 'quiet-luxury', 'cobalt-wash', 'sunlit-studio', 'garden-ledger', 'vector-horizon', 'frontier-gazette',
  'galactic-goth', 'marquee-deco', 'motel-neon', 'ocean-drive', 'mall-sunset', 'quiet-orbit', 'steady-steps', 'malibu-sunset',
  'miami-beach-deco', 'vegas-modern', 'smoky-mountain-autumn', 'childhood-nostalgia', 'long-conversation', 'before-dawn',
  'mountain-rhinestone', 'field-manual', 'blue-hour-chapel', 'woody-creek-winter', 'desert-fever', 'ink-and-seal', 'unbleached-indigo',
  'plain-label',
];

describe('the book of Directions', () => {
  const book = directionsBook();

  it('keeps every Direction that the owner has seen: none of them can leave the Catalog without this test failing', () => {
    expect(KEPT).toHaveLength(38);
    const ids = new Set(DIRECTIONS.map((d) => d.id));
    for (const id of KEPT) {
      expect(ids.has(id), `the Direction "${id}" left the Catalog`).toBe(true);
      expect(book, id).toContain(`(\`${id}\`)`);
    }
  });

  it('names every built-in Direction once, under its group, with its mood, its best uses, and its risk', () => {
    for (const group of DIRECTION_GROUPS) expect(book).toContain(`## ${group.label}`);
    for (const d of DIRECTIONS) {
      expect(book.split(`### ${d.name} (\`${d.id}\`)`).length - 1, d.id).toBe(1);
      expect(book, d.id).toContain(d.mood);
      expect(book, d.id).toContain(d.bestFor);
      expect(book, d.id).toContain(d.risk);
    }
  });

  it('writes each Direction’s design settings as code, value for value', () => {
    for (const d of DIRECTIONS) expect(book, d.id).toContain(JSON.stringify(d.params, null, 2));
  });

  it('writes each Direction’s colors, type, and spacing as the same CSS custom properties that its tokens.css holds', () => {
    for (const d of DIRECTIONS) {
      const project = applyDirection(createProject('Book'), d);
      const css = deriveTokens(project.params, project.a11y).css;
      for (const [name, value] of Object.entries(css)) expect(book, `${d.id} ${name}`).toContain(`  ${name}: ${value};`);
    }
  });

  it('writes the main colors of each Skin of each Direction', () => {
    for (const d of DIRECTIONS) {
      for (const skin of skinsOf(d)) {
        const project = applyDirection(createProject('Book'), d, skin.id);
        const css = deriveTokens(project.params, project.a11y).css;
        expect(book, `${d.id} ${skin.id}`).toContain(`| ${skin.name} | \`${String(css['--bg'])}\` | \`${String(css['--surface'])}\` | \`${String(css['--text'])}\` | \`${String(css['--accent'])}\` | \`${String(css['--accent-2'])}\` | \`${String(css['--btn-fill'])}\` |`);
      }
    }
  });

  it('says what it is, that a program writes it, and that the owner’s own Directions are not in it', () => {
    expect(book).toMatch(/^# The Directions of Refraction Studio, in code\n/);
    expect(book).toContain('Do not edit this file by hand');
    expect(book).toContain('Your own Directions are not in this file');
    expect(book).not.toMatch(/\b20\d\d-\d\d-\d\d\b/);
    expect(book).not.toMatch(/\baccessible\b|\bcompliant\b/i);
  });

  it('is the same file every time', () => {
    expect(directionsBook()).toBe(book);
  });

  it('is stored in docs/reference/directions.md exactly as the core writes it today', async () => {
    await expect(book).toMatchFileSnapshot('../../../docs/reference/directions.md');
  });
});
